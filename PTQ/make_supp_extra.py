#!/usr/bin/env python3
"""Two supplementary tables for quantities that were computed but never shown.

  Table S38  permutation importance of the selector's features, both corpora,
             from results/v83/permimp_{cifar10,imagenet100}.txt
  Table S39  distribution of the constrained-winner latency across all six
             measured devices, from the flagship join -- the generational
             spread that the main paper quotes only two numbers from

Writes results/v83/supp_extra.tex, which Supplementary.tex \\input's after the
flagship section, so the two tables are numbered S38 and S39.

    python make_supp_extra.py
"""
import ast
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "results" / "v83" / "supp_extra.tex"

PRETTY = {
    "dev_soc": "SoC string",
    "device": "Device identity",
    "accdrop_int8": "Accuracy drop, static INT8",
    "accdrop_dynamic": "Accuracy drop, dynamic INT8",
    "accdrop_mixed": "Accuracy drop, mixed",
    "accdrop_fp16": "Accuracy drop, FP16",
    "acc_dynamic": "Accuracy, dynamic INT8",
    "acc_int8": "Accuracy, static INT8",
    "acc_fp32": "Accuracy, FP32",
    "size_int8_kib": "Artifact size, static INT8",
    "size_dynamic_kib": "Artifact size, dynamic INT8",
    "size_mixed_kib": "Artifact size, mixed",
    "size_fp32_kib": "Artifact size, FP32",
    "size_fp16_kib": "Artifact size, FP16",
    "in_px": "Input pixels",
    "dev_cores": "CPU cores",
    "dev_ram_gb": "RAM",
}
DEV_LAB = {
    "USB_Redmi13": "Redmi 13 (Helio G91)",
    "USB_Pixel4": "Pixel 4 (SD 855)",
    "USB_TabS7": "Tab S7+ (SD 865+)",
    "MTK_D9400": "Tab S11 (Dimensity 9400)",
    "S25": "Galaxy S25 (8 Elite)",
    "S26": "Galaxy S26 (8 Elite Gen 5)",
}


def read_importance(path):
    txt = path.read_text()
    m = re.search(r"top features:\s*(\[.*\])", txt, re.S)
    raw = re.sub(r"np\.float64\(([^)]*)\)", r"\1", m.group(1))
    return ast.literal_eval(raw)


def main():
    c10 = dict(read_importance(HERE / "results" / "v83" / "permimp_cifar10.txt"))
    im = dict(read_importance(HERE / "results" / "v83" /
                              "permimp_imagenet100.txt"))
    feats = list(c10) + [f for f in im if f not in c10]
    feats.sort(key=lambda f: -max(c10.get(f, 0), im.get(f, 0)))

    L = ["% Generated by analysis/make_supp_extra.py -- do not edit by hand.",
         "% Cited as Tables S38 and S39 from Paper.tex; keep the order stable.",
         ""]
    L += [r"\begin{table}[!htbp]", r"\centering",
          r"\caption{Permutation importance of the selector's features "
          r"(drop in exact-match accuracy when one feature is shuffled, "
          r"architecture-grouped folds, one seed). Hardware identity dominates "
          r"both corpora, ahead of any model-side feature, which is the "
          r"quantitative form of the accelerator result of "
          r"Section~\ref{M-sec:accel}. ``---'' marks a feature outside that "
          r"corpus's top eight.}",
          r"\label{tab:permimp}", r"\footnotesize",
          r"\begin{tabular}{@{}lcc@{}}", r"\toprule",
          r"\textbf{Feature} & \textbf{CIFAR-10} & \textbf{ImageNet-100} \\",
          r"\midrule"]
    for f in feats:
        a = f"{c10[f]:.3f}" if f in c10 else "---"
        b = f"{im[f]:.3f}" if f in im else "---"
        L.append(f"{PRETTY.get(f, f.replace('_', r'\_'))} & {a} & {b} \\\\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]

    fl = json.load((HERE / "results" / "flagship_2026" /
                    "flagship_corrected.json").open())
    w = fl["winner_latency_ms"]
    order = fl["device_order"]
    med = {d: w[d]["median"] for d in order}
    hi, lo = max(med.values()), min(med.values())
    L += [r"\begin{table}[!htbp]", r"\centering",
          rf"\caption{{Latency of the accuracy-constrained winner on the frozen "
          rf"ImageNet-100 subset, for all six measured devices: the same models "
          rf"and the same selection rule throughout. The median spans "
          rf"{hi / lo:.0f}$\times$ across the hardware. Absolute "
          rf"milliseconds are not comparable between the three measurement "
          rf"harnesses (Table~\ref{{tab:supp-stack-control}}); the column to "
          rf"read is the shape of each distribution.}}",
          r"\label{tab:winlat}", r"\footnotesize",
          r"\setlength{\tabcolsep}{4pt}",
          r"\begin{tabular}{@{}lrrrrrr@{}}", r"\toprule",
          r"\textbf{Device} & $N$ & min & Q1 & median & Q3 & max \\",
          r"\midrule"]
    for d in order:
        v = w[d]
        L.append(f"{DEV_LAB.get(d, d)} & {v['n']} & {v['min']:.3f} & "
                 f"{v['q1']:.3f} & {v['median']:.3f} & {v['q3']:.3f} & "
                 f"{v['max']:.1f} \\\\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    cal = json.load((HERE / "results" / "flagship_2026" /
                     "calibration_new_devices.json").open())
    CL = {"S25": "Galaxy S25", "S26": "Galaxy S26", "MTK_D9400": "Tab S11"}
    L += [r"\begin{table}[!htbp]", r"\centering",
          r"\caption{Transfer of the selector to the three 2025--2026 devices. "
          r"The model is trained on every ImageNet-100 row of the three "
          r"main-campaign devices plus $k$ freeze models benchmarked on the "
          r"target, and tested on the remaining freeze models (5 seeds, "
          r"feasibility-masked, offline features). It transfers to the Tab~S11, "
          r"which is measured with the same harness, but not to the two AI~Hub "
          r"flagships, where a one-line device default is far better and "
          r"calibrating on up to $100$ models does not close the gap.}",
          r"\label{tab:caltransfer}", r"\footnotesize",
          r"\setlength{\tabcolsep}{4pt}",
          r"\begin{tabular}{@{}lrrrr@{}}", r"\toprule",
          r"\textbf{Target} & \textbf{Policy} & $N$ & exact \% & regret \% \\",
          r"\midrule"]
    for dev in ("S25", "S26", "MTK_D9400"):
        d = cal[dev]
        ks = sorted(int(k) for k in d["k"])
        first = True
        for k in ks:
            v = d["k"][str(k)]
            nm = CL[dev] if first else ""
            first = False
            lab = "selector, no calibration" if k == 0 else f"selector, $k={k}$"
            L.append(f"{nm} & {lab} & {v['n_test']} & {v['exact']:.1f} & "
                     f"{v['geo']:.1f} \\\\")
        for nm2, v in d["baselines"].items():
            L.append(f" & {nm2.replace('_', ' ')} & {d['n_models']} & "
                     f"{v['exact']:.1f} & {v['geo']:.1f} \\\\")
        L.append(r"\addlinespace[2pt]")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    OUT.write_text("\n".join(L))
    print("ok ", OUT)
    print(f"    permutation importance: {len(feats)} features")
    print(f"    winner latency: {len(order)} devices, median spread "
          f"{hi / lo:.1f}x ({lo:.3f}-{hi:.3f} ms)")


if __name__ == "__main__":
    main()
